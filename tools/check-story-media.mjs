import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import vm from 'node:vm';
import { TopicStoryMedia as Media } from '../lib/topic-story-media.mjs';
import { TopicStoryContentManager as Content } from '../lib/topic-story-content.mjs';
import { readTopicZip } from '../lib/topic-importer.mjs';
import { TopicTranslations, topicSourceRevision } from '../lib/topic-translations.mjs';
import { scanZipContents } from '../lib/zip-content-scan.mjs';
const require = createRequire(import.meta.url);
globalThis.DOMParser = require(process.argv[2] || 'linkedom').DOMParser;
const original = '<style>/* keep bytes */ p {color:red} .x{background:linear-gradient(90deg,red,blue)}</style><article><h1>Title</h1><p>One <a href="https://example.org/">link</a>.</p><p>Two</p><p>Three</p></article>';
const inserted = Media.insertions(original,[{src:'https://example.org/photo.webp',afterParagraph:2,width:60,align:'right',caption:'Photo'}],{allowedSources:new Set(['https://example.org/photo.webp'])});
const doc = Content.parse(inserted);
assert.equal(doc.body.querySelectorAll('p')[1].nextElementSibling.tagName,'FIGURE');
assert.equal(doc.body.querySelector('img').getAttribute('src'),'https://example.org/photo.webp');
assert.ok(inserted.includes('/* keep bytes */ p {color:red}'));
assert.throws(()=>Media.insertions(original,[{src:'https://invented.invalid/image.png'}],{allowedSources:new Set()}),/supplied/);
assert.throws(()=>Media.insertions(original,[{src:'assets/a.png',afterParagraph:9}]),/does not exist/);
for (const src of ['javascript:alert(1)','//example.org/a.png','assets/../a.png','https://user:pass@example.org/a.png']) assert.equal(Media.safeSource(src),'');
const video = Media.insertions(inserted,[{src:'assets/demo.webm',kind:'video',autoplay:true,loop:true,width:90}]);
const videoNode = Content.parse(video).body.querySelector('video');
for (const name of ['muted','autoplay','loop','playsinline','controls']) assert.ok(videoNode.hasAttribute(name));
assert.ok(!Media.modify(video,1).includes('<video'));
const edited = Media.modify(inserted,0,{src:'https://example.org/photo.webp',width:40,caption:'Changed'});
assert.equal(Media.list(edited)[0].caption,'Changed');
const translated = await Media.translate(video,'fr',async text=>({text:'FR '+text,provider:'browser'}));
assert.ok(translated.html.includes('href="https://example.org/"'));
assert.ok(translated.html.includes('FR link'));
assert.ok(translated.html.includes('/* keep bytes */ p {color:red}'));
assert.equal(Content.parse(translated.html).querySelector('video').getAttribute('src'),'assets/demo.webm');
assert.ok(!translated.text.includes('color:red'));
const malicious = await Media.translate(original,'fr',async()=>({text:'<script>alert(1)</script>',provider:'ai'}));
assert.equal(Content.parse(malicious.html).querySelector('script'),null);
await assert.rejects(Media.translate(original,'fr',async()=>({text:'unchanged',provider:'original'})),/unavailable/);
await assert.rejects(Media.translate(original,'fr',async()=>({text:'FR',provider:'ai'}),{isActive:()=>false}),/cancelled/);
const svg = '<svg xmlns="http://www.w3.org/2000/svg"><defs><linearGradient id="g"><stop stop-color="red"/></linearGradient></defs><rect fill="url(#g)" width="10" height="10"/></svg>';
const bytes = new TextEncoder().encode(svg);
assert.equal(scanZipContents(new Map([['image.svg',bytes]]),bytes.length).passed,true);
assert.equal(scanZipContents(new Map([['bad.svg',new TextEncoder().encode('<svg><script>alert(1)</script></svg>')]]),20).passed,false);
assert.equal(scanZipContents(new Map([['bad.svg',new TextEncoder().encode('<svg><rect fill="url(https://bad.invalid/x)"/></svg>')]]),20).passed,false);
const source = (await readFile(new URL('../lib/topic-exporter.js',import.meta.url),'utf8')).replace(/^import[^;]+;\r?\n/gm,'').replace(/^export /gm,'');
const context = vm.createContext({Blob,TextEncoder,Uint8Array,DataView,TopicTranslations,topicSourceRevision,atob,URL,window:{location:{href:'https://www.topic.earth/'}}});
vm.runInContext(source+'\nglobalThis.packageTopics=buildTopicPackage;',context);
const topic = {id:'media-test',title:'Media test',lat:50,lon:5,category:'climate',language:'en',topicStory:{enabled:true,html:'<article><p>One</p><img src="assets/image.svg"></article>',assets:[{path:'assets/image.svg',url:'data:image/svg+xml;base64,'+Buffer.from(svg).toString('base64')}]}};
const packaged = await context.packageTopics([topic]);
const imported = (await readTopicZip(packaged.blob))[0];
assert.match(imported.topicStory.assets[0].url,/^data:image\/svg\+xml;base64,/);
assert.ok(Media.resolve(imported.topicStory.html,imported.topicStory.assets).includes('data:image/svg+xml;base64,'));
const again = await context.packageTopics([imported]);
assert.equal((await readTopicZip(again.blob))[0].topicStory.assets[0].path,'assets/image.svg');
console.log('Paragraph insertion, media edits/playback, source validation, markup-preserving translation, SVG scanning and ZIP asset round-trip passed.');
const appSource = (await readFile(new URL('../app.main.js',import.meta.url),'utf8')).split('// Initialize application when DOM is ready')[0].replace(/^import[^;]+;\r?\n/gm,'');
const appContext = vm.createContext({TopicStoryMedia:Media,Blob,URL,window:{location:{origin:'https://www.topic.earth'}},
  Settings:{get:()=>({translationLanguage:'fr'})},LanguageManager:{normalizeLanguageCode:code=>code.split('-')[0],getSpeechCode:code=>code,getLanguageInfo:()=>({nativeName:'Français'})},
  ReadTranslationService:{translateText:async text=>({text:'FR '+text,provider:'browser'})}});
vm.runInContext(appSource+'\nglobalThis.App=TopicEarthApp;',appContext);
const app = Object.create(appContext.App.prototype);
app.detailPanel={wrapTopicStoryHtml:html=>'<!doctype html><html lang="en"><head></head><body>'+html+'</body></html>'};
app.showTTSVignette=state=>{app.ttsVignetteState={...state,id:1};};
app.updateTTSVignette=update=>Object.assign(app.ttsVignetteState,update);
app.isActiveTTSVignette=()=>true;
let spoken=''; app.speakFromVignette=text=>spoken=text;
await app.openStoryReadingPopup(topic,{html:original+'<img src="/assets/example.webp">'});
assert.ok(spoken.includes('FR One'));
assert.equal(app.ttsVignetteState.storyLanguage,'fr');
let htmlDownload;
app.downloadVignetteFile=(blob,extension,state)=>{htmlDownload={blob,extension,state};};
app.saveVignetteHTML();
assert.equal(htmlDownload.extension,'html');
assert.equal(htmlDownload.state.speechLang,'fr');
assert.ok((await htmlDownload.blob.text()).includes('https://www.topic.earth/assets/example.webp'));
assert.ok((await htmlDownload.blob.text()).includes('/* keep bytes */'));
appContext.ReadTranslationService.translateText=async text=>({text,provider:'original'});
await app.openStoryReadingPopup(topic,{html:original});
assert.equal(app.ttsVignetteState.storyLanguage,'en');
assert.ok(app.ttsVignetteState.status.includes('Original HTML kept'));
app.saveVignetteHTML();assert.equal(htmlDownload.state.speechLang,'en');
console.log('Story reading uses document text; translated HTML download preserves CSS/media and unavailable translation keeps source-language naming.');
