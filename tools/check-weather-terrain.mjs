import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
// Browser .js modules are ESM even though the root Node package is CommonJS.
const moduleUrl = text => `data:text/javascript;base64,${Buffer.from(text).toString('base64')}`;
const meteoUrl = moduleUrl(await readFile(new URL('../lib/meteo-realtime.js', import.meta.url), 'utf8'));
const {buildMeteoWatchLocations,fetchRealtimeMeteoSnapshot,meteoMetricLines} = await import(meteoUrl);
const weatherSource = (await readFile(new URL('../lib/weather-visuals.mjs', import.meta.url), 'utf8'))
  .replace(/'\.\/meteo-realtime\.js\?[^']*'/, JSON.stringify(meteoUrl));
const {weatherSymbolSvg,weatherPreviewHtml} = await import(moduleUrl(weatherSource));
import {horizontalDistance,segmentSlope,elevationLabel,TerrainMeasureManager} from '../lib/terrain-measure.mjs';
const locations=buildMeteoWatchLocations({now:0,regionalContext:{lat:50,lon:4,label:'Regional test'}});
assert.ok(locations.length<=32);
for(const name of ['New York','Los Angeles','Beijing','Algiers','Moscow','Kyiv'])assert.ok(locations.some(p=>p.name===name));
assert.equal(locations.filter(p=>p.isRegionalFocus).length,5);
const scan=buildMeteoWatchLocations({now:900000});
assert.notEqual(scan.find(p=>p.id.startsWith('scan-')).lon,locations.find(p=>p.id.startsWith('scan-')).lon);
let requested;
const snapshot=await fetchRealtimeMeteoSnapshot({now:0,fetchImpl:async url=>{requested=new URL(url);return {ok:true,json:async()=>requested.searchParams.get('latitude').split(',').map((lat,index)=>({current:{time:'2026-10-15T18:00',temperature_2m:18,weather_code:1,cloud_cover:10,wind_speed_10m:20,wind_gusts_10m:index===1?110:20},hourly:{wind_gusts_10m:[index===1?110:20],wind_speed_10m:[20],temperature_2m:[18]}}))}}});
assert.equal(snapshot.live,true);assert.ok(snapshot.worldPoints.length<=24);
const event=snapshot.eventPoints.find(p=>p.eventType==='wind');assert.ok(event);
assert.ok(meteoMetricLines(event).includes('Gust max 110 km/h'));
assert.ok(weatherPreviewHtml(event).includes('110 km/h'));
assert.ok(!weatherSymbolSvg(event).includes('<rect'));
assert.ok(!weatherSymbolSvg(event).includes('💨'));
assert.equal(new Set(snapshot.points.map(p=>`${p.lat},${p.lon}`)).size,snapshot.points.length);
assert.equal(Math.round(horizontalDistance([0,0],[0,1])),111195);
const slope=segmentSlope([0,0],[0,.001],0,1);
assert.ok(Math.abs(slope.percent-.8993)<.001);assert.ok(slope.degrees>0);
assert.equal(segmentSlope([0,0],[0,0],0,1),null);
assert.equal(segmentSlope([0,0],[0,1],null,1),null);
assert.equal(elevationLabel(.64),'64 cm');assert.equal(elevationLabel(-1),'-100 cm');
let calls=0;const manager=new TerrainMeasureManager(async()=>{calls++;return {ok:true,json:async()=>({elevation:[12.5]})}});
assert.deepEqual(await Promise.all([manager.elevation([50,4]),manager.elevation([50,4])]),[12.5,12.5]);assert.equal(calls,1);
await manager.elevation([50,4]);assert.equal(calls,1);
await assert.rejects(manager.elevation([95,4]));
const missing=new TerrainMeasureManager(async()=>({ok:true,json:async()=>({elevation:[null]})}));await assert.rejects(missing.elevation([0,0]));
console.log('Coverage cap, city anchors, regional samples, rotating cells, warning values, transparent symbols, elevations, signed slopes and missing-data handling passed.');

const {default:vm}=await import('node:vm');
let regionalSource=await readFile(new URL('../components/RegionalMap.js',import.meta.url),'utf8');
regionalSource=regionalSource.replace(/^import[^\r\n]*;\r?\n/gm,'').replace('export class RegionalMap','class RegionalMap');
const context=vm.createContext({console,TerrainMeasureManager,elevationLabel,segmentSlope});
vm.runInContext(regionalSource+'\nglobalThis.TestMap=RegionalMap',context);
const map=Object.create(context.TestMap.prototype),output={hidden:true,textContent:''};
map.visible=true;map.element={querySelector:()=>output};
map.terrainMeasure={elevation:async pair=>pair[1]===0?1:2};
await map.updateTerrainReadout([[0,0],[0,.001]]);
assert.ok(output.textContent.includes('100 cm'));assert.ok(output.textContent.includes('/100'));assert.ok(output.textContent.includes('90 m grid'));
await map.updateTerrainReadout([]);assert.equal(output.hidden,true);
let release;map.terrainMeasure={elevation:pair=>pair[1]===0?new Promise(resolve=>release=resolve):Promise.resolve(42)};
const stale=map.updateTerrainReadout([[0,0]]);await map.updateTerrainReadout([[0,1]]);release(1);await stale;
assert.ok(output.textContent.includes('4,200 cm'));
console.log('Regional terrain readout, clear and stale-result rejection passed.');
